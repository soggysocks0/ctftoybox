_WINDOWS_ROLLBACK = r"""# Best-effort rollback — does NOT fully revert policy/audit changes.
$ErrorActionPreference = 'SilentlyContinue'

Write-Host '[*] Removing local user jdoe (if present)...'
Remove-LocalUser -Name 'jdoe'

Write-Host '[*] Removing SMB shares...'
foreach ($n in 'Files','LabShare') { Remove-SmbShare -Name $n -Force }

Write-Host '[*] Removing custom service CTFLabSvc and folder...'
sc.exe stop   CTFLabSvc
sc.exe delete CTFLabSvc
Remove-Item -Recurse -Force 'C:\Program Files\CTFLab'

Write-Host '[*] Removing scheduled task and ProgramData folder...'
schtasks /Delete /TN CTFLabHousekeep /F
Remove-Item -Recurse -Force 'C:\ProgramData\CTFLab'

Write-Host '[*] Clearing Winlogon AutoAdmin remnants...'
$wl = 'HKLM:\SOFTWARE\Microsoft\Windows NT\CurrentVersion\Winlogon'
Remove-ItemProperty -Path $wl -Name DefaultPassword
Remove-ItemProperty -Path $wl -Name DefaultUserName
Remove-ItemProperty -Path $wl -Name AutoAdminLogon

Write-Host '[*] Removing planted lab files / FTP root / SMB share dir...'
Remove-Item -Recurse -Force 'C:\Files'
Remove-Item -Recurse -Force 'C:\Lab'
Remove-Item -Recurse -Force 'C:\ftp'

Write-Host 'Rollback complete (best-effort). Audit policy and Defender state were not changed.'
"""

_LINUX_ROLLBACK = r"""#!/usr/bin/env bash
# Best-effort rollback — does NOT fully revert auditd / AppArmor / UFW state.
set +e

echo '[*] Removing user jdoe...'
userdel -r jdoe 2>/dev/null

echo '[*] Removing planted artifacts...'
rm -rf /srv/backup /srv/samba/public /srv/ftp/anon
rm -rf /opt/app   /opt/ctflab        /var/log/ctflab-heartbeat.log
rm -f  /etc/sudoers.d/99-ctfmgr-nmap
rm -f  /etc/cron.d/ctflab-housekeep
rm -f  /usr/local/bin/ctflab-backup
rm -rf /tmp/ctflab-backup-input /tmp/ctflab-backup.tar

echo '[*] Removing share entry from smb.conf (if present)...'
sed -i '/\[public\]/,/^$/d' /etc/samba/smb.conf 2>/dev/null
systemctl restart smbd 2>/dev/null

echo '[*] Removing webroot lab files...'
rm -rf /var/www/html/.git /var/www/html/backup /var/www/html/share
rm -f  /var/www/html/config.php~

echo '[*] Removing fail2ban / auditd rules we added (services left installed)...'
rm -f /etc/fail2ban/jail.d/ctflab.local
rm -f /etc/audit/rules.d/ctflab.rules
systemctl restart fail2ban 2>/dev/null
augenrules --load >/dev/null 2>&1 || true

echo 'Rollback complete (best-effort).'
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def generate_template_bundle(
    template: SystemTemplate,
    service_ids: list[str],
    output_dir: str,
) -> Path:
    """
    Write all generated files for a system template into `output_dir`.
    Returns the resolved Path.
    """
    folder = _ensure_dir(Path(output_dir))

    # Resolve services (and quietly drop any that don't apply to this OS)
    services: list[LiveService] = []
    for sid in service_ids:
        s = get_service(sid)
        if s is None:
            continue
        if template.target_os not in s.supported_os:
            continue
        services.append(s)

    is_windows = template.target_os is TargetOS.WINDOWS_11
    try:
        if is_windows:
            setup_text = gen_windows.build_setup_script(template, services)
            _write_text(folder / "setup.ps1", setup_text)
            _write_text(folder / "rollback.ps1", _WINDOWS_ROLLBACK)
        else:
            setup_text = gen_linux.build_setup_script(template, services)
            _write_text(folder / "setup.sh",    setup_text,    executable=True)
            _write_text(folder / "rollback.sh", _LINUX_ROLLBACK, executable=True)

        _write_text(folder / "README.md",
                    _build_readme(template, services))
        _write_text(folder / "VULNERABILITIES.md",
                    _build_vulnerabilities_md(template, services))
    except OSError as e:
        raise GenerationError(f"Filesystem error: {e}") from e

    return folder